SPEED, RADIUS, SPACING, EXTENSION, BUDGET = .03, .2, .1, .25, 300.
START = np.array([3.5, 3.5])
HEADING = np.pi/4


def vertices(p):
    cx, cy, angle, height, bottom, top, shear = p
    u = np.array([np.cos(angle), np.sin(angle)])
    v = np.array([-u[1], u[0]])
    local = np.array([[-bottom/2-shear/2, -height/2],
                      [bottom/2-shear/2, -height/2],
                      [top/2+shear/2, height/2], [-top/2+shear/2, height/2]])
    return np.array([cx, cy])+local[:, :1]*u+local[:, 1:]*v


def contains(p, points):
    d = points-p[:2]
    u = np.array([np.cos(p[2]), np.sin(p[2])])
    v = np.array([-u[1], u[0]])
    x, y = d@u, d@v
    t = y/p[3]+.5
    width = p[4]*(1-t)+p[5]*t
    return (t >= 0)&(t <= 1)&(abs(x-p[6]*(t-.5)) <= width/2)


def valid(p):
    z = vertices(p)
    return (.3 <= p[3] <= 2.2 and .4 <= min(p[4:6]) and max(p[4:6]) <= 3.2
            and max(p[4:6])/min(p[4:6]) <= 2.8 and abs(p[6]) <= .7
            and (z >= 1).all() and (z <= 9).all())


def lanes(p, reverse_rows=False, reverse_start=False):
    u = np.array([np.cos(p[2]), np.sin(p[2])]); v = np.array([-u[1], u[0]])
    count = max(1, int(np.ceil(p[3]/SPACING)))
    # Sensor coverage sets row spacing. Visit interleaved rows to allow wider
    # Dubins connectors while still covering every row exactly once.
    rows = .5+(np.arange(count)-(count-1)/2)*SPACING/p[3]
    stride = max(1, int(np.ceil(2*RADIUS/SPACING)))
    order = [j for offset in range(min(stride, count)) for j in range(offset, count, stride)]
    rows = rows[order]
    if reverse_rows:
        rows = rows[::-1]
    result = []
    for i, t in enumerate(rows):
        center = p[:2]+(t-.5)*(p[3]*v+p[6]*u)
        width = (p[4]*(1-t)+p[5]*t)/2+EXTENSION
        left, right = center-width*u, center+width*u
        east = (i % 2 == 0) != reverse_start
        a, b, angle = (left, right, p[2]) if east else (right, left, p[2]+np.pi)
        result.extend([(a, angle), (b, angle)])
    return result


def route(p, start=START, heading=HEADING, detailed=False, only_sweep=False):
    best = None
    for reverse in (False, True):
        for flip in (False, True):
            waypoints = lanes(p, reverse, flip)
            pos, h, length, sweep_length = start.copy(), heading, 0., 0.
            for j, (target, angle) in enumerate(waypoints):
                path = DubinsPath(pos, h, target, angle, RADIUS)
                length += path.length
                if j:
                    sweep_length += path.length
                pos, h = target, angle
            comparison = sweep_length if only_sweep else length
            if best is None or comparison < best[0]:
                best = comparison, waypoints
    seconds = best[0]/SPEED
    if not detailed:
        return seconds
    pos, h = start.copy(), heading
    samples = [[*pos, h]]
    paths = []
    for target, angle in best[1]:
        paths.append(DubinsPath(pos, h, target, angle, RADIUS))
        pos, h = target, angle
    pos, h, index = start.copy(), heading, 0
    while index < len(paths):
        budget = SPEED
        while budget > 1e-10 and index < len(paths):
            pos, h, budget = paths[index].move(pos, h, budget)
            if paths[index].done:
                index += 1
        samples.append([*pos, h])
    return seconds, np.asarray(samples), best[1]


def cheap_time(p):
    rows = max(1, int(np.ceil(p[3]/SPACING)))
    return (rows*((p[4]+p[5])/2+2*EXTENSION)+(rows-1)*np.pi*RADIUS)/SPEED


def weighted_quantile(x, w, q):
    ix = np.argsort(x); c = np.cumsum(w[ix])
    return np.interp(np.asarray(q)*c[-1], c, x[ix])


def seeds(points, mass, k=22):
    centers = [points[int(mass.argmax())]]
    nearest = np.full(len(points), np.inf)
    for _ in range(k-1):
        nearest = np.minimum(nearest, np.square(points-centers[-1]).sum(-1))
        centers.append(points[np.argmax(nearest*np.sqrt(mass))])
    centers = np.array(centers)
    for _ in range(6):
        labels = np.square(points[:, None]-centers[None]).sum(-1).argmin(-1)
        for j in range(k):
            selected = labels == j
            if selected.any():
                centers[j] = np.average(points[selected], axis=0, weights=mass[selected])
    return centers, labels


def generate(points, mass, start, heading, previous=None, count=12, locked_ids=()):
    """Weighted clustering, oriented quantile fits, marginal-coverage selection,
    local geometric refinement and exact Dubins-time feasibility.
    """
    begin = time.perf_counter()
    centers, labels = seeds(points, mass)
    pool = []
    for j, center in enumerate(centers):
        take = labels == j
        x, w = points[take], mass[take]
        if len(x) < 4:
            continue
        d = x-center; cov = (d*w[:, None]).T@d/w.sum()
        _, axes = np.linalg.eigh(cov)
        principal = np.arctan2(axes[1, -1], axes[0, -1])
        for angle in (principal, principal+np.pi/2, principal+np.pi/6, principal-np.pi/6):
            u = np.array([np.cos(angle), np.sin(angle)]); v = np.array([-u[1], u[0]])
            xx, yy = d@u, d@v
            low, mid, high = weighted_quantile(yy, w, [.06, .5, .94])
            widths, offsets = [], []
            for sub in (yy <= mid, yy > mid):
                a, b = weighted_quantile(xx[sub], w[sub], [.06, .94])
                widths.append(max(.5, b-a+.12)); offsets.append((a+b)/2)
            mean = center+(low+high)/2*v+np.mean(offsets)*u
            p = np.array([*mean, angle, max(.4, high-low+.1), *widths, offsets[1]-offsets[0]])
            for scale in (.75, 1., 1.2):
                q = p.copy(); q[3:] *= scale
                for _ in range(9):
                    if valid(q) and cheap_time(q) <= BUDGET:
                        pool.append(q.copy()); break
                    q[3:] *= .9
    # Only in-progress polygons are retained below. Previous idle/completed
    # geometry must not compete with newly generated belief-driven proposals.
    masks = [contains(p, points) for p in pool]
    selected = [deepcopy(old) for old in previous or [] if old['id'] in locked_ids]
    covered = np.zeros(len(points), dtype=bool)
    for item in selected:
        item['mask'] = contains(item['params'], points)
        covered |= item['mask']
    def merit(p, mask):
        new = mass[mask & ~covered].sum()
        overlap = mass[mask & covered].sum()
        # Modest time preference; candidate quality is spatial diversity,
        # not an external replacement for the policy's final decision.
        return (new-.35*overlap)/(max(60., cheap_time(p))/BUDGET)**.35
    for _ in range(max(0, count-len(selected))):
        if not pool:
            break
        order = sorted(range(len(pool)), key=lambda i:merit(pool[i], masks[i]), reverse=True)
        best = None
        for ix in order[:12]:
            p = pool[ix].copy()
            for _ in range(6):
                duration = route(p, start, heading, only_sweep=True)
                if duration <= BUDGET:
                    break
                p[3:] *= .92
            if not valid(p) or duration > BUDGET:
                continue
            mask = contains(p, points)
            value = merit(p, mask)
            if best is None or value > best[0]:
                best = value, p, mask, duration
        if best is None or best[0] <= 0:
            break
        _, p, mask, duration = best
        # Two rounds of coordinate proposals; only leading improvements pay
        # for the exact path calculation. Nothing is adjusted by hand.
        for step in (1., .5):
            alternatives = []
            for dimension, delta in enumerate((.18, .18, np.pi/18, .12, .2, .2, .15)):
                for sign in (-1, 1):
                    q = p.copy(); q[dimension] += sign*delta*step
                    if valid(q) and cheap_time(q) <= BUDGET*1.12:
                        m = contains(q, points)
                        alternatives.append((merit(q, m), q, m))
            alternatives.sort(key=lambda a:a[0], reverse=True)
            current = merit(p, mask)
            for value, q, m in alternatives[:3]:
                if value <= current:
                    break
                seconds = route(q, start, heading, only_sweep=True)
                if seconds <= BUDGET:
                    p, mask, duration = q, m, seconds
                    break
        selected.append(dict(params=p, mask=mask, seconds=duration))
        covered |= mask
        keep = [i for i, m in enumerate(masks) if mass[m & ~covered].sum() > .003*mass.sum()]
        pool = [pool[i] for i in keep]; masks = [masks[i] for i in keep]
    # Spatial matching preserves display IDs between replans, independently
    # of list order. These IDs are not network input features.
    available = {p['id']:p for p in previous or [] if p['id'] not in locked_ids}
    next_id = max((p['id'] for p in previous or []), default=0)+1
    for item in selected:
        if item.get('id') in locked_ids:
            continue
        overlaps = [(int((item['mask'] & old['mask']).sum())/
                     max(1, int((item['mask'] | old['mask']).sum())), key)
                    for key, old in available.items()]
        overlap, key = max(overlaps, default=(0, None))
        if overlap > .25:
            item['id'] = key; del available[key]
        else:
            item['id'] = next_id; next_id += 1
    return selected, 1000*(time.perf_counter()-begin)


def density(belief, points_km):
    x = points_km*10
    background = belief.background_density(x)*100  # per square kilometre
    reported = np.zeros(len(x)); types = background[:, None]*belief.background_type_prior
    for component in belief.components:
        norm = (belief._density(component, belief.integration_points)*belief.integration_weights).sum()
        value = belief._density(component, x)/norm*component['remaining']*100
        reported += value; types[:, component['type']-1] += value
    return reported+background, reported, background, types


def frozen_sensor(position, heading, config):
    pos, angle = np.asarray(position)*10, float(heading)
    def probability(points):
        return detection_probabilities(points, pos[None], np.array([angle]), np.array([True]),
            config.sensor_range, config.sensor_fov_deg, config.detection_probability)[0]
    return probability


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    config = Config.load(ROOT/'configs/belief.json')
    report = dict(position=[60., 60.], type_counts=[1, 1, 1], sigma_hint=10.,
                  log_sigma_std=.5, member_radius=6.5)
    belief = GaussianTargetBelief(config, report)
    side = 64; axis = 1+(np.arange(side)+.5)*8/side
    gx, gy = np.meshgrid(axis, axis); points = np.column_stack((gx.ravel(), gy.ravel()))
    area = (8/side)**2
    cases, previous = [], None
    start, heading = START.copy(), HEADING
    for state in range(3):
        prep = time.perf_counter()
        total, reported, background, types = density(belief, points)
        prep_ms = 1000*(time.perf_counter()-prep)
        proposals, milliseconds = generate(points, total*area, start, heading, previous)
        union = np.zeros(len(points), dtype=bool); sum_mass = 0.; items = []
        for item in proposals:
            p, mask = item['params'], item['mask']
            duration, trajectory, waypoints = route(p, start, heading, True)
            probability_miss = np.ones(len(points))
            # Sensor likelihood is evaluated along the sampled trajectory,
            # including entry and turns. No perfect polygon detection assumption.
            for pose in trajectory:
                probability_miss *= 1-frozen_sensor(pose[:2], pose[2], config)(points*10)
            gain = float((total*(1-probability_miss)).sum()*area)
            mass = float(total[mask].sum()*area); sum_mass += mass; union |= mask
            tm = types[mask].sum(0)*area
            items.append(dict(id=item['id'], vertices=vertices(p).tolist(), params=p.tolist(),
                route=trajectory[:, :2].tolist(), seconds=duration, mass=mass,
                background=float(background[mask].sum()*area), type_mass=tm.tolist(),
                expected_life=float(tm@np.array([2., 1., 1.])/max(mass, 1e-12)),
                expected_detections=gain, lanes=len(waypoints)//2,
                map_exit=bool(((trajectory[:, :2] < 0)|(trajectory[:, :2] > 10)).any())))
        order = np.argsort(reported)[::-1]
        target = .8*reported.sum()
        hot = np.zeros(len(points), dtype=bool)
        if target > 0:
            hot[order[:np.searchsorted(np.cumsum(reported[order]), target)+1]] = True
        title = ['초기 보고', '첫 탐색 경로에서 미검출', 'Type 1 한 개 발견 후'][state]
        case = dict(title=title, total=total.tolist(), reported=reported.tolist(), background=background.tolist(),
            proposals=items, start=start.tolist(), generation_ms=milliseconds, density_ms=prep_ms,
            coverage=float(total[union].sum()/total.sum()),
            hot_coverage=float(reported[hot & union].sum()/max(reported[hot].sum(), 1e-12)),
            duplicate_mass=float(sum_mass-total[union].sum()*area),
            remaining=belief.remaining_types.tolist(), tracks=[(t['mean']*10).tolist() for t in belief.tracks])
        cases.append(case)
        print(title, 'generation_ms', round(milliseconds, 1), 'density_ms', round(prep_ms, 1),
              'coverage', round(case['coverage'], 3), 'hot', round(case['hot_coverage'], 3), flush=True)
        if state == 0:
            _, trajectory, _ = route(proposals[0]['params'], start, heading, True)
            for t, pose in enumerate(trajectory):
                belief.update(frozen_sensor(pose[:2], pose[2], config), [], t)
            start, heading = trajectory[-1, :2].copy(), float(trajectory[-1, 2])
        elif state == 1:
            # A controlled sensor event, not a generated policy success.
            belief.update(lambda x:np.zeros(len(x)), [(500, np.array([62., 59.]), 1, 2)], 400)
        previous = proposals
    payload = dict(side=side, cases=cases, budget_seconds=BUDGET, speed_km_s=SPEED,
                   radius_km=RADIUS, lane_spacing_km=SPACING,
                   scope='Controlled belief-update demonstration; no policy or hidden-truth rollout.')
    (OUT/'demo.json').write_text(json.dumps(payload, ensure_ascii=False, indent=2))
    plot(cases, side)
    (OUT/'demo.html').write_text(HTML.replace('__DATA__', json.dumps(payload, ensure_ascii=False)))
    print(OUT/'demo.html', flush=True)


def plot(cases, side):
    fig, axes = plt.subplots(1, 3, figsize=(18, 6), constrained_layout=True)
    colors = plt.get_cmap('tab20')
    maximum = max(max(c['total']) for c in cases)
    titles = ['Initial report', 'After an empty sensor sweep', 'After one Type 1 detection']
    for ax, case, title in zip(axes, cases, titles):
        ax.imshow(np.asarray(case['total']).reshape(side, side), extent=[1, 9, 1, 9], origin='lower',
                  cmap='Blues', vmin=0, vmax=maximum)
        for p in case['proposals']:
            z = np.asarray(p['vertices']); color = colors((p['id']-1)%20)
            ax.add_patch(Polygon(z, fill=False, edgecolor=color, linewidth=1.6))
            ax.text(*z.mean(0), str(p['id']), color=color, ha='center', weight='bold', fontsize=9)
        route_points = np.asarray(case['proposals'][0]['route'])
        ax.plot(*route_points.T, color='#de671a', lw=1., alpha=.85)
        ax.scatter(*case['start'], marker='^', color='#de671a', s=50)
        for position in case['tracks']:
            ax.scatter(*position, marker='*', color='#d7263d', s=140)
        ax.set(xlim=(0, 10), ylim=(0, 10), aspect='equal', xlabel='km', ylabel='km',
               title=f'{title}\nTotal mass coverage {case["coverage"]:.0%} | high-belief coverage {case["hot_coverage"]:.0%}')
    fig.suptitle('Belief-driven trapezoids · actual Dubins lawnmower · 300 s per candidate', fontsize=15)
    fig.savefig(OUT/'overview.png', dpi=170)
    fig.savefig(OUT/'overview.pdf')
    plt.close(fig)


